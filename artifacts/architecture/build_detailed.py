    f.panel(45,785,1710,470,'State / Data Path',DATA)

    # Controller boundary includes the real count register.
    f.rect(275,157,665,205,GRAY,CTRL)
    f.text(295,184,'Controller',22,CTRL,bold=True)
    f.text(295,209,'u_controller : controller',15,CTRL)
    f.block(310,232,275,97,'Phase / Control Logic','phase[1:0], done\nIDLE / EXPAND / ROUND',CTRL,GRAY,19)
    f.block(625,232,280,97,'Round Counter','count[3:0] : 0 ... 9',CTRL,GRAY,20)
    f.path([(585,263),(625,263)],CTRL,dash=True)
    f.path([(660,329),(660,343),(470,343),(470,329)],CTRL,dash=True)
    for y,label in [(235,'clk'),(273,'rst'),(310,'start')]:
        f.text(88,y-8,label,19,CTRL)
        f.path([(88,y),(275,y)],CTRL,dash=True)
    f.path([(940,173),(1660,173)],CTRL,dash=True)
    f.label(1690,179,'busy',19,CTRL)
    f.path([(940,207),(1660,207)],CTRL,dash=True)
    f.label(1690,213,'done',19,CTRL)

    f.rect(1030,232,390,130,'white',CTRL)
    f.text(1225,260,'Round Index Generator',21,CTRL,anchor='middle',bold=True)
    f.block(1065,282,315,57,'+1 Incrementer','',CTRL,GRAY,21)
    f.path([(905,303),(1065,303)],CTRL,dash=True)
    f.label(980,288,'count[3:0]',16,CTRL)
    f.path([(1380,312),(1635,312)],CTRL,dash=True)
    f.label(1560,292,'round_index[3:0]',17,CTRL)
    f.text(1490,341,'count + 1',16,CTRL)
    for x,label in [(420,'data_sel[1:0]'),(675,'key_step'),(875,'final_step')]:
        f.path([(x,362),(x,391)],CTRL,dash=True)
        f.label(x,409,label,17,CTRL)

    # Round-key datapath.
    f.rect(365,525,260,125,GOLD,KEY)
    f.text(495,553,'Previous Key MUX',21,KEY,anchor='middle',bold=True)
    f.text(390,584,'count = 0: key',17,KEY)

def build_round():
    f=Figure(1500,1350,'AES Round Architecture',
             'round | one combinational datapath reused across all 10 encryption rounds',2)
    f.rect(335,140,820,1055,'white',DATA,width=1.5)
    f.text(365,174,'u_round : round',20,DATA,bold=True)
    x=670
    f.text(x,125,'state_in[127:0]',21,DATA,anchor='middle')
    f.path([(x,134),(x,210)],DATA,width=3)
    f.block(470,210,400,128,'SubBytes','u_sub_bytes : sub_bytes\n16 parallel S-box instances\nEach: asynchronous 256 × 8-bit ROM',DATA,BLUE,25)
    f.path([(x,338),(x,420)],DATA,width=3)
    f.label(x,383,'after_sub[127:0]',18,DATA)
    f.block(470,420,400,111,'ShiftRows','u_shift_rows : shift_rows\nFixed byte permutation | column-major',DATA,BLUE,25)
    f.path([(x,531),(x,625)],DATA,width=3)
    f.label(x,571,'after_shift[127:0]',18,DATA)
    f.dot(x,593,DATA)
    f.block(470,625,400,121,'MixColumns','u_mix_columns : mix_columns\n4 parallel 32-bit column transforms\nCombinational GF(2^8) transform',DATA,BLUE,25)
    f.path([(x,746),(x,852)],DATA,width=3)
    f.label(x,795,'after_mix[127:0]',18,DATA)
    # The physical bypass begins AFTER ShiftRows, before MixColumns.
    f.path([(x,593),(1040,593),(1040,898),(870,898)],DATA,width=3.5)
    f.label(1028,562,'Final-round bypass',19,DATA)
    f.label(1040,758,'after_shift',17,DATA)
    f.text(1080,786,'128',15,DATA,anchor='middle')
    f.rect(470,852,400,111,BLUE,DATA)
    f.text(x,885,'Final-Round MUX',25,DATA,anchor='middle',bold=True)
    f.text(x,917,'0: after_mix    |    1: after_shift',18,DATA,anchor='middle')
    f.text(x,943,'before_key = final_round ? after_shift : after_mix',14,DATA,anchor='middle')
    f.text(63,885,'final_round',20,CTRL)
    f.text(63,914,'from top-level final_step',16,CTRL)
    f.path([(63,930),(307,930),(307,908),(470,908)],CTRL,dash=True)
    f.path([(x,963),(x,1054)],DATA,width=3)
    f.label(x,1011,'before_key[127:0]',18,DATA)
    f.block(470,1054,400,100,'AddRoundKey','u_add_round_key : add_round_key\n128-bit XOR',DATA,BLUE,25)
    f.path([(1310,1098),(870,1098)],KEY,width=3)
    f.label(1250,1073,'round_key[127:0]',20,KEY)
    f.path([(x,1154),(x,1220)],DATA,width=3)
    f.label(x,1247,'state_out[127:0]',21,DATA)
    f.text(1215,325,'Round selection',20,INK,bold=True)
    f.text(1215,359,'Rounds 1-9:',18,INK)
    f.text(1215,386,'final_round = 0',17,CTRL)
    f.text(1215,425,'Round 10:',18,INK)
    f.text(1215,452,'final_round = 1',17,CTRL)
    f.text(45,1281,'No internal state registers or pipeline stages. MixColumns is bypassed by selection; no clock gating is present.',17,MUTED)
    f.footer('Sources: rtl/core/round.v; sub_bytes.v; shift_rows.v; mix_columns.v; add_round_key.v; sbox_byte.v')
    return f.save('02_aes_round')


def build_key():
    f=Figure(1650,1150,'Key Expansion Architecture',
             'key_expansion | one combinational 128-bit round-key update | round_index = 1 ... 10',3)
    f.panel(45,133,1560,380,'Key schedule transform',KEY)
    f.panel(45,548,1560,395,'32-bit XOR chain',KEY)
    f.text(85,212,'old_key[127:0]',22,KEY,bold=True)
    f.text(85,245,'Word split (wiring)',18,KEY)
    f.text(85,280,'[127:96]  [95:64]',18,KEY)
    f.text(85,310,'[63:32]   [31:0]',18,KEY)
    f.path([(278,304),(375,304)],KEY,width=3)
    f.label(325,276,'[31:0]',17,KEY)
    f.block(375,245,270,112,'RotWord','{old_key[23:0],\n old_key[31:24]}',KEY,GOLD,24)
    f.path([(645,304),(795,304)],KEY,width=3)
    f.label(720,282,'rotated[31:0]',17,KEY)
    f.block(795,245,275,112,'SubWord','4 parallel sbox_byte instances\nEach: async 256 × 8-bit ROM',KEY,GOLD,24)
    f.path([(1070,304),(1277,304)],KEY,width=3)
    f.label(1175,279,'substituted[31:0]',17,KEY)
    f.xor(1300,304,23,KEY)
    f.path([(1323,304),(1530,304)],KEY,width=3)
    f.label(1450,280,'temp[31:0]',19,KEY)
    f.text(1300,218,'Rcon addition',18,KEY,anchor='middle')
    f.block(765,412,305,70,'Rcon Selector','Combinational case(round_index)',CTRL,GRAY,21)
    f.path([(462,447),(765,447)],CTRL,dash=True)
    f.label(598,430,'round_index[3:0]',18,CTRL)
    f.path([(1070,447),(1300,447),(1300,327)],KEY,width=2.5)
    f.label(1200,474,'{rcon[7:0], 24\'h0}',17,KEY)
    f.path([(1450,304),(1450,528),(50,528),(50,680),(258,680)],KEY,width=3)
    f.dot(1450,304,KEY)
    f.label(367,522,'temp[31:0]',17,KEY)
    # Cascaded XORs are combinational. Old-word names use the actual bit slices.
    xs=[280,655,1030,1405]
    slices=['old_key[127:96]','old_key[95:64]','old_key[63:32]','old_key[31:0]']
    for i,(x,s) in enumerate(zip(xs,slices)):
        f.text(x,611,s,19,KEY,anchor='middle')
        f.path([(x,627),(x,658)],KEY,width=3)
        f.xor(x,680,22,KEY)
        f.path([(x+22,680),(x+96,680)],KEY,width=3,arrow=False)
        f.dot(x+83,680,KEY)
        f.label(x+77,657,f'w{i}[31:0]',17,KEY)
        if i<3:f.path([(x+96,680),(xs[i+1]-22,680)],KEY,width=3)
        f.path([(x+83,680),(x+83,826)],KEY,width=2.5)
    f.block(215,826,1290,82,'Concatenate','new_key[127:0] = {w0, w1, w2, w3}',KEY,GOLD,22)
    f.path([(860,908),(860,999)],KEY,width=3)
    f.label(860,984,'new_key[127:0]',22,KEY)
    f.text(860,1030,'Top-level net: next_key[127:0]',18,KEY,anchor='middle')
    f.text(70,750,'w0 = old_key[127:96] ^ temp',17,KEY)
    f.text(70,781,'w1 = old_key[95:64] ^ w0',17,KEY)
    f.text(825,750,'w2 = old_key[63:32] ^ w1',17,KEY)
    f.text(825,781,'w3 = old_key[31:0] ^ w2',17,KEY)
    f.text(70,1077,'No key registers inside this module. Rcon is selected from constants; all XOR-chain values are combinational.',17,MUTED)
    f.footer('Sources: rtl/core/key_expansion.v; rtl/core/sbox_byte.v; rtl/core/includes/xtime.vh')
    return f.save('03_key_expansion')


if __name__=='__main__':
    for fn in [build_top,build_round,build_key]:print(fn())

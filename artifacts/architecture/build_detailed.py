    f.text(1445,557,'Round Key Registers',23,KEY,anchor='middle',bold=True)
    f.text(1445,585,'(10 × 128-bit)',21,KEY,anchor='middle')
    f.text(1445,612,'round_keys[1:10]',18,KEY,anchor='middle')
    f.text(1445,637,'Write enable: key_step',16,KEY,anchor='middle')
    f.text(78,553,'key[127:0]',19,KEY)
    f.path([(78,568),(365,568)],KEY,width=3)
    f.dot(245,568,KEY)
    f.path([(625,588),(815,588)],KEY,width=3)
    f.label(720,573,'old_key[127:0]',17,KEY)
    f.path([(1100,588),(1250,588)],KEY,width=3)
    f.label(1175,566,'next_key',17,KEY)
    f.text(1175,612,'128',15,KEY,anchor='middle')
    f.path([(1340,650),(1340,714),(310,714),(310,617),(365,617)],KEY,width=3.5)
    f.label(840,704,'Previous-key feedback: round_keys[count][127:0]',18,KEY)
    f.path([(495,488),(495,525)],CTRL,dash=True)
    f.label(495,487,'count[3:0]',16,CTRL)
    f.path([(970,488),(970,525)],CTRL,dash=True)
    f.label(970,487,'round_index[3:0]',16,CTRL)
    f.path([(1325,488),(1325,525)],CTRL,dash=True)
    f.label(1325,487,'round_index[3:0]',16,CTRL)
    f.path([(1535,488),(1535,525)],CTRL,dash=True)
    f.label(1535,487,'key_step / clk',16,CTRL)
    f.path([(1460,714),(1460,650)],CTRL,dash=True)
    f.label(1460,739,'count[3:0]',16,CTRL)
    f.text(1100,743,'Write: round_keys[round_index] <= next_key',15,KEY,anchor='end')


    f.dot(1300,1050,DATA)
    f.label(1307,1030,'128',15,DATA)
    f.path([(1300,1050),(1300,946),(1680,946)],DATA,width=3)
    f.label(1460,930,'data_out[127:0]',19,DATA)
    f.path([(1605,1052),(1670,1052),(1670,1225),(620,1225),(620,1095),(680,1095)],DATA,width=3.8)
    f.label(1132,1210,'Round feedback: round_result[127:0] | reused for 10 rounds',18,DATA)
    f.path([(1125,1105),(1125,1178),(650,1178),(650,1135),(680,1135)],DATA,width=2.5)
    f.label(1020,1160,'State hold / data_out',16,DATA)

    f.label(1580,867,'[round_index]',17,KEY)
    f.label(1611,898,'128',15,KEY)

    f.path([(70,1297),(130,1297)],DATA,width=3.5)
    f.text(141,1303,'State / Data',16,DATA)
    f.path([(322,1297),(382,1297)],KEY,width=3)
    f.text(393,1303,'Round Key',16,KEY)
    f.path([(556,1297),(616,1297)],CTRL,dash=True)
    f.text(627,1303,'Control / address / clock',16,CTRL)
    f.text(1748,1303,'Matching control labels denote the same net.',16,MUTED,anchor='end')
    f.text(70,1335,'rst: synchronous, active high; resets Controller and State Register only. Round Key Registers have no reset.',16,MUTED)
